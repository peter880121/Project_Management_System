DROP PROCEDURE IF EXISTS rag_modes_rollback_check;
CREATE PROCEDURE rag_modes_rollback_check()
BEGIN
 IF EXISTS(SELECT 1 FROM RagMessage WHERE mode<>'INTERNAL' OR intent IS NOT NULL OR webQuery IS NOT NULL LIMIT 1)
 OR EXISTS(SELECT 1 FROM RagCitation WHERE sourceType='WEB' OR webUrl IS NOT NULL LIMIT 1)
 OR EXISTS(SELECT 1 FROM AuditLog WHERE action IN ('RAG_WEB_SEARCH_CONFIRMED','RAG_WEB_SEARCH_STARTED') LIMIT 1) THEN
  SIGNAL SQLSTATE '45000' SET MYSQL_ERRNO=1644, MESSAGE_TEXT='RAG_MODES_ROLLBACK_BLOCKED_PRESERVE_EVIDENCE';
 END IF;
END;
CALL rag_modes_rollback_check();
DROP PROCEDURE rag_modes_rollback_check;
ALTER TABLE RagCitation DROP COLUMN webUrl, DROP COLUMN retrievedAt, DROP COLUMN publishedAt;
ALTER TABLE RagMessage DROP COLUMN mode, DROP COLUMN intent, DROP COLUMN webQuery;
