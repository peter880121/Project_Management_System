-- Destructive rollback is permitted only before any managed requirement/evidence exists.
DROP PROCEDURE IF EXISTS medpm_requirements_rollback;
CREATE PROCEDURE medpm_requirements_rollback() BEGIN
IF EXISTS(SELECT 1 FROM Requirement WHERE managed=TRUE) OR EXISTS(SELECT 1 FROM RequirementIntake) OR EXISTS(SELECT 1 FROM RequirementRevision) OR EXISTS(SELECT 1 FROM RequirementChangeRequest) OR EXISTS(SELECT 1 FROM RequirementTaskLink) OR EXISTS(SELECT 1 FROM RequirementDecision) OR EXISTS(SELECT 1 FROM TestExecution) OR EXISTS(SELECT 1 FROM RequirementBaseline) OR EXISTS(SELECT 1 FROM RequirementAttachment) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Requirement evidence exists; rollback refused'; END IF;
DROP TRIGGER IF EXISTS freeze_RequirementAttachment_insert;
DROP TRIGGER IF EXISTS freeze_RequirementAttachment_update;
DROP TRIGGER IF EXISTS freeze_RequirementAttachment_delete;
DROP TRIGGER IF EXISTS freeze_RequirementBaseline_insert;
DROP TRIGGER IF EXISTS freeze_RequirementBaseline_update;
DROP TRIGGER IF EXISTS freeze_RequirementBaseline_delete;
DROP TRIGGER IF EXISTS freeze_TestExecution_insert;
DROP TRIGGER IF EXISTS freeze_TestExecution_update;
DROP TRIGGER IF EXISTS freeze_TestExecution_delete;
DROP TRIGGER IF EXISTS freeze_RequirementDecision_insert;
DROP TRIGGER IF EXISTS freeze_RequirementDecision_update;
DROP TRIGGER IF EXISTS freeze_RequirementDecision_delete;
DROP TRIGGER IF EXISTS freeze_RequirementTaskLink_insert;
DROP TRIGGER IF EXISTS freeze_RequirementTaskLink_update;
DROP TRIGGER IF EXISTS freeze_RequirementTaskLink_delete;
DROP TRIGGER IF EXISTS freeze_RequirementChangeRequest_insert;
DROP TRIGGER IF EXISTS freeze_RequirementChangeRequest_update;
DROP TRIGGER IF EXISTS freeze_RequirementChangeRequest_delete;
DROP TRIGGER IF EXISTS freeze_RequirementRevision_insert;
DROP TRIGGER IF EXISTS freeze_RequirementRevision_update;
DROP TRIGGER IF EXISTS freeze_RequirementRevision_delete;
DROP TRIGGER IF EXISTS freeze_RequirementIntake_insert;
DROP TRIGGER IF EXISTS freeze_RequirementIntake_update;
DROP TRIGGER IF EXISTS freeze_RequirementIntake_delete;
DROP TABLE RequirementAttachment;
DROP TABLE TestExecution;
DROP TABLE RequirementDecision;
DROP TABLE RequirementTaskLink;
DROP TABLE RequirementChangeRequest;
DROP TABLE RequirementRevision;
DROP TABLE RequirementIntake;
DROP TABLE RequirementBaseline;
ALTER TABLE Requirement DROP INDEX Requirement_projectId_number_key, DROP INDEX Requirement_projectId_workflowState_dueDate_idx, DROP COLUMN `approvedVersion`, DROP COLUMN `category`, DROP COLUMN `completedAt`, DROP COLUMN `createdById`, DROP COLUMN `discoveryPhase`, DROP COLUMN `draftVersion`, DROP COLUMN `dueDate`, DROP COLUMN `managed`, DROP COLUMN `number`, DROP COLUMN `ownerId`, DROP COLUMN `priority`, DROP COLUMN `riskLevel`, DROP COLUMN `rowVersion`, DROP COLUMN `targetRelease`, DROP COLUMN `workflowState`;
END;
CALL medpm_requirements_rollback();
DROP PROCEDURE medpm_requirements_rollback;
