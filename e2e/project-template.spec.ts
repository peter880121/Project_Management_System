import { randomUUID } from "node:crypto";
import { PrismaClient } from "@prisma/client";
import { expect, test } from "@playwright/test";
import { createSessionToken } from "../src/modules/auth/session-token";
import { STANDARD_PROJECT_TASKS, STANDARD_PROJECT_TEMPLATE } from "../src/modules/projects/templates";

const db = new PrismaClient();
test.use({ channel: process.env.ACCEPTANCE_EDGE === "1" ? "msedge" : undefined });
test.afterAll(() => db.$disconnect());

for (const initialize of [true, false]) {
  test(`PM creates ${initialize ? "standard WBS" : "empty project"} and lands on its board`, async ({ page, context, baseURL }) => {
    const actorId = "00000000-0000-4000-8000-000000000002";
    await context.addCookies([{ name: "medpm_session", value: createSessionToken(actorId, Date.now() + 3_600_000), url: baseURL!, httpOnly: true, sameSite: "Lax" }]);
    await page.goto("/projects/new");
    const name = `Synthetic template ${randomUUID()}`;
    await page.getByLabel("项目名称", { exact: true }).fill(name);
    const checkbox = page.getByRole("checkbox", { name: "自动按标准模板初始化阶段任务", exact: true });
    await expect(checkbox).toBeChecked();
    if (!initialize) await checkbox.uncheck();
    const created = page.waitForResponse(response => response.request().method() === "POST" && new URL(response.url()).pathname === "/api/projects");
    await page.getByRole("button", { name: "创建项目", exact: true }).click();
    const response = await created;
    expect(response.status()).toBe(201);
    const projectId = (await response.json()).data.id;
    await page.waitForURL(url => url.pathname === `/projects/${projectId}/board`);
    await expect(page.getByRole("heading", { name, exact: true })).toBeVisible();
    const tasks = await db.task.findMany({ where: { projectId } });
    expect(tasks).toHaveLength(initialize ? 14 : 0);
    const audits = await db.auditLog.findMany({ where: { projectId } });
    expect(audits.filter(log => log.action === "PROJECT_CREATED")).toHaveLength(1);
    expect(audits.filter(log => log.action === "TASK_CREATED")).toHaveLength(initialize ? 14 : 0);
    if (initialize) {
      const edges = await db.taskDependency.findMany({ where: { task: { projectId } } });
      expect(edges).toHaveLength(13);
      for (const [index, template] of STANDARD_PROJECT_TASKS.entries()) {
        const task = tasks.find(row => row.title === template.title)!;
        expect(task.status).toBe("TODO");
        expect(Number(task.estimateHours)).toBe(template.estimateHours);
        expect(task.description).toContain(`所属阶段：${template.phase}`);
        expect(task.assigneeId).toBeNull();
        expect(task.dueDate).toBeNull();
        const prerequisites = edges.filter(edge => edge.taskId === task.id).map(edge => edge.dependsOnTaskId);
        expect(prerequisites).toEqual(index === 0 ? [] : [tasks.find(row => row.title === STANDARD_PROJECT_TASKS[index - 1].title)!.id]);
        const audit = audits.find(log => log.entityId === task.id && log.action === "TASK_CREATED")!;
        expect(audit.actorId).toBe(actorId);
        expect(audit.userAgent).toBeTruthy();
        expect(audit.after).toMatchObject({ autoGenerated: true, phase: template.phase, template: STANDARD_PROJECT_TEMPLATE, dependencyIds: prerequisites });
        await expect(page.getByRole("link", { name: template.title, exact: true })).toBeVisible();
      }
    }
  });
}

test("creation API rejects non-PM roles and malformed template flags", async ({ page, context, baseURL }) => {
  const request = page.request;
  for (const suffix of ["1", "3", "4"]) {
    await context.addCookies([{ name: "medpm_session", value: createSessionToken(`00000000-0000-4000-8000-00000000000${suffix}`, Date.now() + 3_600_000), url: baseURL!, httpOnly: true, sameSite: "Lax" }]);
    expect((await request.post("/api/projects", { data: { name: "Synthetic forbidden" } })).status()).toBe(403);
  }
  await context.addCookies([{ name: "medpm_session", value: createSessionToken("00000000-0000-4000-8000-000000000002", Date.now() + 3_600_000), url: baseURL!, httpOnly: true, sameSite: "Lax" }]);
  expect((await request.post("/api/projects", { data: { name: "Synthetic invalid", initializeStandardTasks: "false" } })).status()).toBe(400);
});
