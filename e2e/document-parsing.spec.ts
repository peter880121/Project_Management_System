import { randomUUID } from "node:crypto";
import { PrismaClient } from "@prisma/client";
import { expect, test } from "@playwright/test";
import { hashPassword } from "../src/modules/auth/password";
import { syntheticPdf } from "../tests/fixtures/pdf";
const db = new PrismaClient(); const runId = randomUUID();
const emails = [`parse-test-${runId}-pm@medpm.local`, `parse-test-${runId}-qa@medpm.local`];
let password: string; let projectId: string;
test.beforeAll(async () => {
  password = process.env.LOCAL_DEV_SEED_PASSWORD || ""; if (!password) throw new Error("Set LOCAL_DEV_SEED_PASSWORD before parse E2E");
  const passwordHash = await hashPassword(password);
  await db.$transaction(async (tx) => {
    const pm = await tx.user.create({ data: { email: emails[0], name: "Synthetic parser PM", role: "PM", status: "ACTIVE", passwordHash } });
    const qa = await tx.user.create({ data: { email: emails[1], name: "Synthetic parser QA", role: "QA", status: "ACTIVE", passwordHash } });
    projectId = (await tx.project.create({ data: { name: "Synthetic cloud parser acceptance", ownerId: pm.id } })).id;
    await tx.projectMember.create({ data: { projectId, userId: qa.id } });
  });
});
test.afterAll(async () => { try { await db.$transaction((tx) => tx.session.deleteMany({ where: { user: { email: { in: emails } } } })); } finally { await db.$disconnect(); } });
test("PM queues a PDF; worker parses asynchronously; QA previews cited content and downloads source", async ({ page }) => {
  test.setTimeout(240000);
  expect((await page.request.post("/api/auth/login", { data: { email: emails[0], password } })).status()).toBe(200);
  await page.goto(`/projects/${projectId}/documents`);
  const bytes = syntheticPdf();
  await page.getByLabel("选择 PDF", { exact: true }).setInputFiles({ name: "synthetic-release.pdf", mimeType: "application/pdf", buffer: bytes });
  await page.getByRole("checkbox", { name: "确认文件仅含合成数据，不含真实患者信息", exact: true }).check();
  await page.getByRole("button", { name: "上传文档", exact: true }).click();
  await expect(page.getByText(/可下载/)).toBeVisible({ timeout: 20000 });
  const row = page.locator("article").filter({ has: page.getByRole("heading", { name: "synthetic-release.pdf", exact: true }) });
  await row.getByRole("checkbox", { name: /确认将此合成 PDF/ }).check();
  const submitted = page.waitForResponse((response) => /\/parse$/.test(new URL(response.url()).pathname) && response.request().method() === "POST");
  await row.getByRole("button", { name: "开始解析", exact: true }).click();
  const response = await submitted; expect(response.status()).toBe(202);
  const job = (await response.json()).data;
  const requestBody = response.request().postDataJSON();
  const documentId = new URL(response.url()).pathname.split("/").at(-2)!;
  const duplicate = await page.request.post(`/api/documents/${documentId}/parse`, { data: requestBody });
  expect(duplicate.status()).toBe(202); expect((await duplicate.json()).data.id).toBe(job.id);
  await expect.poll(async () => {
    const data = (await (await page.request.get(`/api/documents/${documentId}/parse`)).json()).data;
    const current = data.find((value: { id: string }) => value.id === job.id);
    if (current?.status === "FAILED") throw new Error(`Parse failed: ${current.errorCode}`);
    return current?.status;
  }, { timeout: 180000, intervals: [2000, 3000, 5000] }).toBe("SUCCEEDED");
  await row.getByRole("button", { name: "刷新解析任务", exact: true }).click();
  await expect(row.getByRole("button", { name: "预览解析结果", exact: true })).toBeVisible();
  await row.getByRole("button", { name: "预览解析结果", exact: true }).click();
  await expect(row.getByRole("heading", { name: "解析预览 v1", exact: true })).toBeVisible();
  await expect(row.locator("pre")).toContainText("Synthetic release requirement");
  expect((await page.request.post("/api/auth/logout")).status()).toBe(200);
  expect((await page.request.post("/api/auth/login", { data: { email: emails[1], password } })).status()).toBe(200);
  expect((await page.request.post(`/api/documents/${documentId}/parse`, { data: { requestKey: randomUUID(), expectedVersion: 1, cloudProcessingConfirmed: true } })).status()).toBe(403);
  const preview = await page.request.get(`/api/documents/${documentId}/preview`); expect(preview.status()).toBe(200);
  const parsed = (await preview.json()).data; expect(parsed.markdown).toContain("Synthetic release requirement");
  expect(parsed).not.toHaveProperty("uploadUrl"); expect(parsed).not.toHaveProperty("resultKey");
  expect(await (await page.request.get(`/api/documents/${documentId}/download`)).body()).toEqual(bytes);
  const stored = await db.documentParseJob.findUniqueOrThrow({ where: { id: job.id } }); expect(stored.resultSha256).toMatch(/^[a-f0-9]{64}$/); expect(stored.resultKey).toBeTruthy();
  expect(await db.auditLog.count({ where: { entityId: job.id, action: "DOCUMENT_PARSE_REQUESTED" } })).toBe(1);
  expect(await db.auditLog.count({ where: { entityId: job.id, action: "DOCUMENT_PARSE_SUCCEEDED" } })).toBe(1);
});
